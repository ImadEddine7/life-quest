const STAGES = [
  { minLevel: 1, sprite: NOVICE, label: 'Novice' },
  { minLevel: 5, sprite: APPRENTICE, label: 'Apprentice' },
  { minLevel: 10, sprite: WARRIOR, label: 'Warrior' },
  { minLevel: 15, sprite: KNIGHT, label: 'Knight' },
  { minLevel: 20, sprite: CHAMPION, label: 'Champion' },
  { minLevel: 30, sprite: LEGEND, label: 'Legend' },
]

export function getAvatarForLevel(level: number): { pixels: string[][]; label: string } {
  let stage = STAGES[0]
  for (const s of STAGES) {
    if (level >= s.minLevel) stage = s
  }
  const pixels = stage.sprite.map(row =>
    row.split('').map(char => PALETTE[char] || '')
  )
  return { pixels, label: stage.label }
}
